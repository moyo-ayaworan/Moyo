function getLocalizedTranslation(path: string, lang: LanguageCode): string {
    const keys = path.split('.');
    let result: unknown = localizedTranslations[translationFallbacks[lang]];

    for (const key of keys) {
        if (result && typeof result === 'object' && key in result) {
            result = (result as Record<string, unknown>)[key];
        } else {
            return '';
        }
    }

    return typeof result === 'string' ? result : '';
}

export function useTranslate(lang: LanguageCode) {
    const t = (path: string): string => {
        const keys = path.split('.');
        let result: unknown = localizedTranslations[translationFallbacks[lang]];
        for (const key of keys) {
            if (result && typeof result === 'object' && key in result) {
                result = (result as Record<string, unknown>)[key];
            } else {
                let fallback: unknown = localizedTranslations.EN;
                for (const fallbackKey of keys) {
                    if (fallback && typeof fallback === 'object' && fallbackKey in fallback) {
                        fallback = (fallback as Record<string, unknown>)[fallbackKey];
                    } else {
                        return path;
                    }
                }
                return typeof fallback === 'string' ? translateDynamicText(fallback, lang) : path;
            }
        }
        return typeof result === 'string' ? translateDynamicText(result, lang) : path;
    };

    const translateText = (value: string): string => translateDynamicText(value, lang);

    return { t, translateText };
}

function normalizeDynamicText(value: string): string {
    return value
        .replace(/[’‘]/g, "'")
        .replace(/[“”]/g, '"')
        .replace(/\s+/g, ' ')
        .trim()
        .replace(/^["']|["']$/g, '')
        .replace(/[.!?]+$/g, '')
        .toLowerCase();
}

function matchCapitalization(source: string, translated: string): string {
    if (!translated) return translated;
    if (source.length > 1 && source === source.toUpperCase()) return translated.toUpperCase();
    if (source[0] === source[0]?.toUpperCase()) {
        return translated.charAt(0).toUpperCase() + translated.slice(1);
    }
    return translated;
}

function isProtectedDynamicWord(word: string): boolean {
    return /^[IVXLCDM]+$/i.test(word);
}

export function translateDynamicText(value: string | null | undefined, lang: LanguageCode): string {
    if (!value) return '';
    if (lang === 'EN') return value;

    const dictionary = dynamicTextTranslations[lang];
    if (!dictionary) return value;

    const normalizedValue = normalizeDynamicText(value);
    const exact = dictionary[normalizedValue];
    if (exact) return exact;

    const defaultSettingPath = defaultSiteSettingTranslationPaths[normalizedValue];
    if (defaultSettingPath) {
        const defaultSettingTranslation = getLocalizedTranslation(defaultSettingPath, lang);
        if (defaultSettingTranslation) return defaultSettingTranslation;
    }

    const words = value.match(/[A-Za-z][A-Za-z'-]*/g) ?? [];
    const canTranslateWithoutMixing = words.every((word) => {
        const normalizedWord = normalizeDynamicText(word);
        return Boolean(dictionary[normalizedWord]) || isProtectedDynamicWord(word);
    });

    if (words.length > 1 && !canTranslateWithoutMixing) {
        return value;
    }

    return value.replace(/[A-Za-z][A-Za-z'-]*/g, (word) => {
        const normalizedWord = normalizeDynamicText(word);
        const translated = dictionary[normalizedWord];
        return translated ? matchCapitalization(word, translated) : word;
    });
}
